    public static void main(String[] args) throws Exception {

        long start = System.currentTimeMillis();

        try (Connection connection = DriverManager.getConnection(URL, USER, PASSWORD)) {

            connection.setAutoCommit(false);

            String insertNoIndex =
                    "INSERT INTO person_no_index(name, salary, age, gender) VALUES (?, ?, ?, ?)";

            String insertWithIndex =
                    "INSERT INTO person_with_index(name, salary, age, gender) VALUES (?, ?, ?, ?)";

            try (PreparedStatement psNoIndex = connection.prepareStatement(insertNoIndex);
                 PreparedStatement psWithIndex = connection.prepareStatement(insertWithIndex)) {

                ThreadLocalRandom random = ThreadLocalRandom.current();

                for (int i = 1; i <= TOTAL_ROWS; i++) {

                    boolean isMale = random.nextBoolean();

                    String fullName = generateFullName(random, isMale);
                    String gender = isMale ? "Male" : "Female";

                    int salary = random.nextInt(30_000, 230_000);
                    int age = random.nextInt(18, 78);

                    // --- без индекса ---
                    psNoIndex.setString(1, fullName);
                    psNoIndex.setInt(2, salary);
                    psNoIndex.setInt(3, age);
                    psNoIndex.setString(4, gender);
                    psNoIndex.addBatch();

                    // --- с индексом ---
                    psWithIndex.setString(1, fullName);
                    psWithIndex.setInt(2, salary);
                    psWithIndex.setInt(3, age);
                    psWithIndex.setString(4, gender);
                    psWithIndex.addBatch();

                    if (i % BATCH_SIZE == 0) {
                        psNoIndex.executeBatch();
                        psWithIndex.executeBatch();
                        connection.commit();
                    }

                    if (i % 100_000 == 0) {
                        System.out.println("Inserted: " + i);
                    }
                }

                psNoIndex.executeBatch();
                psWithIndex.executeBatch();
                connection.commit();
            }
        }

        long end = System.currentTimeMillis();
        System.out.println("Finished in " + (end - start) / 1000 + " seconds");
    }

    private static String generateFullName(ThreadLocalRandom random, boolean isMale) {

        String lastName = isMale
                ? MALE_LAST[random.nextInt(MALE_LAST.length)]
                : FEMALE_LAST[random.nextInt(FEMALE_LAST.length)];

        String firstName = isMale
                ? MALE_FIRST[random.nextInt(MALE_FIRST.length)]
                : FEMALE_FIRST[random.nextInt(FEMALE_FIRST.length)];

        String middleName = isMale
                ? MALE_MIDDLE[random.nextInt(MALE_MIDDLE.length)]
                : FEMALE_MIDDLE[random.nextInt(FEMALE_MIDDLE.length)];

        return lastName + " " + firstName + " " + middleName;
    }
